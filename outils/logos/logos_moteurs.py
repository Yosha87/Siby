"""Engine logos for the Engines window (tcl/moderne/logosmoteurs.tcl).

Sources in outils/logos/moteurs/: toby.png (Toby's icon, Yosha's), stockfish.png
(the official icon, stockfishchess.org/images/logo/icon_128x128.png), leela.jpg
(Leela Chess Zero's logo). "Other engine" is drawn here (a chip), and so is
Alter Ego (a white bust in front of its pink double, Toby's neon style;
Yosha 2026-11-10).
Sizes 48, 72 and 96 pixels (screen scaling), embedded as base64 PNG.

Usage: python3 outils/logos/logos_moteurs.py   (from the repository root)
"""
import base64, io, os
from PIL import Image, ImageDraw, ImageFilter

ICI = os.path.dirname(os.path.abspath(__file__))
SORTIE = os.path.join(ICI, '..', '..', 'siby', 'tcl', 'moderne', 'logosmoteurs.tcl')
TAILLES = (48, 72, 96)


def arrondi(im, rayon):
    """Rounded corners (transparent outside)."""
    im = im.convert('RGBA')
    m = Image.new('L', im.size, 0)
    ImageDraw.Draw(m).rounded_rectangle([0, 0, im.size[0] - 1, im.size[1] - 1], rayon, fill=255)
    a = Image.new('L', im.size, 0)
    a.paste(im.getchannel('A'), (0, 0), m)
    im.putalpha(a)
    return im


def puce(t):
    """'Other engine': a processor chip, light grey on a dark rounded square."""
    k = 4
    T = t * k
    im = Image.new('RGBA', (T, T), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, T - 1, T - 1], T // 6, fill=(56, 56, 56, 255))
    c, w = T // 2, T * 0.26
    gris = (200, 200, 200, 255)
    for i in (-1, 0, 1):
        o = i * T * 0.13
        for (x0, y0, x1, y1) in ((c + o, c - w - T * .1, c + o, c - w), (c + o, c + w, c + o, c + w + T * .1),
                                 (c - w - T * .1, c + o, c - w, c + o), (c + w, c + o, c + w + T * .1, c + o)):
            d.line([x0, y0, x1, y1], fill=gris, width=max(2, T // 28))
    d.rounded_rectangle([c - w, c - w, c + w, c + w], T // 20, outline=gris, width=max(2, T // 24))
    d.rectangle([c - w * .45, c - w * .45, c + w * .45, c + w * .45], fill=gris)
    return im.resize((t, t), Image.LANCZOS)


def alterego(t):
    """Alter Ego: a human (white) in front of their double in Toby's pink,
    neon lines on Toby's black rounded tile."""
    S = 512
    noir = (5, 6, 7, 255)

    def buste(d, cx, cy, s, coul, fond=None):
        r = 0.18 * s
        d.ellipse((cx - r, cy - 0.42 * s - r, cx + r, cy - 0.42 * s + r), fill=fond, outline=coul, width=30)
        d.chord((cx - 0.40 * s, cy - 0.10 * s, cx + 0.40 * s, cy + 0.70 * s), 180, 360, fill=fond, outline=coul, width=30)

    def neon(cx, cy, coul, fond=None):
        lay = Image.new('RGBA', (S, S), (0, 0, 0, 0))
        buste(ImageDraw.Draw(lay), cx, cy, 400, coul, fond)
        halo = lay.filter(ImageFilter.GaussianBlur(18))
        out = Image.alpha_composite(Image.new('RGBA', (S, S), (0, 0, 0, 0)), halo)
        out = Image.alpha_composite(out, halo)
        return Image.alpha_composite(out, lay)

    im = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle((0, 0, S - 1, S - 1), radius=90, fill=noir)
    im = Image.alpha_composite(im, neon(318, 318, (255, 122, 184, 255)))
    im = Image.alpha_composite(im, neon(205, 350, (240, 244, 248, 255), noir))
    return im.resize((t, t), Image.LANCZOS)


def b64(im):
    f = io.BytesIO()
    im.save(f, 'PNG', optimize=True)
    return base64.b64encode(f.getvalue()).decode()


lignes = ['###', '### Siby: engine logos for the Engines window (generated by',
          '### outils/logos/logos_moteurs.py: do not edit by hand)', '###', '',
          'namespace eval ::moderne::logosmoteurs {', '  variable donnees', '  array set donnees {}', '}', '']
sources = {'toby': 'toby.png', 'stockfish': 'stockfish.png', 'leela': 'leela.jpg'}
for cle in ('toby', 'stockfish', 'leela', 'autre', 'alterego'):
    for t in TAILLES:
        if cle == 'autre':
            im = puce(t)
        elif cle == 'alterego':
            im = alterego(t)
        else:
            im = Image.open(os.path.join(ICI, 'moteurs', sources[cle])).convert('RGBA').resize((t, t), Image.LANCZOS)
            if cle == 'leela':
                im = arrondi(im, t // 6)
        lignes.append(f'set ::moderne::logosmoteurs::donnees({cle},{t}) {{{b64(im)}}}')
lignes += ['', '### Tk image of an engine logo (toby, stockfish, leela, autre, alterego), about',
           '### 48 points: the stored size closest to the screen scaling',
           'proc ::moderne::logosmoteurs::image {cle} {', '  variable donnees',
           '  set s [expr {max(1.0, [tk scaling] * 72 / 96.0)}]', '  set t 48',
           '  foreach x {48 72 96} { if {abs($x - 48 * $s) < abs($t - 48 * $s)} { set t $x } }',
           '  set img ::moderne::logosmoteurs::$cle$t', '  if {$img ni [::image names]} {',
           '    if {![info exists donnees($cle,$t)]} { return {} }',
           '    ::image create photo $img -format png -data $donnees($cle,$t)', '  }', '  return $img', '}', '',
           '### End of Siby', '']
open(SORTIE, 'w').write('\n'.join(lignes))
print('written', SORTIE, os.path.getsize(SORTIE), 'bytes')
