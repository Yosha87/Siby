#!/bin/sh
# Downloads free piece sets of Lichess (SVG, lila repository) and renders
# them as PNG strips in siby/bitmaps/pieces/<set>/<size>.png (12
# pieces: wp wn wb wr wq wk bp bn bb br bq bk), loaded by Siby when the set
# is chosen (tcl/moderne/pieces.tcl). Only sets under a free license
# (GPL, AGPL, Apache, MIT, CC BY, CC BY-SA, CC0): see LISEZMOI.md.
# Dependencies: curl, rsvg-convert (librsvg2-bin), ImageMagick (convert).
set -e
RACINE=$(cd "$(dirname "$0")/.." && pwd)
SORTIE="$RACINE/siby/bitmaps/pieces"
TAILLES="25 30 35 40 45 50 55 60 65 70 75 80 90 100 110 120 130 140 150 160"
URL=https://raw.githubusercontent.com/lichess-org/lila/master/public/piece
# set|Name shown|author|license
JEUX='merida|Merida|Armando Hernandez Marroquin|GPL v2+
chessnut|Chessnut|Alexis Luengas|Apache 2.0
pirouetti|Pirouetti|pirouetti|AGPL v3+
mpchess|MPChess|Maxime Chupin|GPL v3+
fantasy|Fantasy|Maurizio Monge|MIT
spatial|Spatial|Maurizio Monge|MIT
celtic|Celtic|Maurizio Monge|MIT
firi|Firi|James Faure|CC BY 4.0
letter|Letter|usolando|AGPL v3+'
TMP=$(mktemp -d)
mkdir -p "$SORTIE"
{
  echo "# Piece sets of Lichess (free licenses)"
  echo
  echo "SVG source: Lichess repository, \`public/piece/<set>/\`"
  echo "(https://github.com/lichess-org/lila/tree/master/public/piece), see lila's"
  echo "\`COPYING.md\`. PNG strips generated by \`outils/generer_pieces_lichess.sh\`."
  echo
  echo "| Set | Author | License |"
  echo "|---|---|---|"
} > "$SORTIE/LISEZMOI.md"
echo "$JEUX" | while IFS='|' read -r jeu nom auteur licence; do
  dossier=$jeu
  mkdir -p "$SORTIE/$jeu" "$TMP/$jeu"
  for p in wP wN wB wR wQ wK bP bN bB bR bQ bK; do
    curl -sSf -o "$TMP/$jeu/$p.svg" "$URL/$dossier/$p.svg"
  done
  for t in $TAILLES; do
    for p in wP wN wB wR wQ wK bP bN bB bR bQ bK; do
      rsvg-convert -w "$t" -h "$t" "$TMP/$jeu/$p.svg" -o "$TMP/$p.png"
    done
    convert "$TMP/wP.png" "$TMP/wN.png" "$TMP/wB.png" "$TMP/wR.png" "$TMP/wQ.png" "$TMP/wK.png" \
            "$TMP/bP.png" "$TMP/bN.png" "$TMP/bB.png" "$TMP/bR.png" "$TMP/bQ.png" "$TMP/bK.png" \
            -background none +append -strip "PNG32:$SORTIE/$jeu/$t.png"
  done
  echo "$nom" > "$SORTIE/$jeu/nom.txt"
  echo "| $nom (\`$jeu\`) | $auteur | $licence |" >> "$SORTIE/LISEZMOI.md"
  echo "$jeu: ok"
done
rm -rf "$TMP"
du -sh "$SORTIE"
