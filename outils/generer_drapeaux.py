def principal(dossier):
    pays = json.load(open(os.path.join(dossier, "country.json"), encoding="utf-8"))
    noms = {}
    for p in pays:
        noms[p["name"].lower()] = p["code"]
    noms.update(ALIAS)
    lignes = [
        "###",
        "### drapeaux.tcl: country flags (Siby), generated by outils/generer_drapeaux.py",
        "### Flags: flag-icons (https://github.com/lipis/flag-icons), MIT licence,",
        f"### rasterised to {LARGEUR}x{HAUTEUR} PNG.",
        "###",
        "",
        "namespace eval ::moderne::drapeaux {",
        "  variable donnees",
        "  array set donnees {}",
        "  variable noms",
        "  array set noms {}",
        "}",
        "",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for p in sorted(pays, key=lambda x: x["code"]):
            svg = os.path.join(dossier, p["flag_4x3"])
            png = os.path.join(tmp, p["code"] + ".png")
            subprocess.run(["rsvg-convert", "-w", str(LARGEUR), "-h", str(HAUTEUR), "-o", png, svg], check=True)
            b64 = base64.b64encode(open(png, "rb").read()).decode()
            lignes.append(f"set ::moderne::drapeaux::donnees({p['code']}) {{{b64}}}")
    lignes.append("")
    lignes.append("array set ::moderne::drapeaux::noms {")
    for n in sorted(noms):
        lignes.append(f"  {{{n}}} {noms[n]}")
    lignes.append("}")
    lignes.append("")
    lignes.append("### End Siby")
    open(SORTIE, "w", encoding="utf-8").write("\n".join(lignes) + "\n")
    print(f"{len(pays)} flags, {len(noms)} names -> {os.path.relpath(SORTIE)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    principal(sys.argv[1])
