#!/usr/bin/env python3
"""Generates siby/tcl/moderne/icones.tcl: SCID's toolbar icons
redrawn with Tabler Icons (https://tabler.io/icons, MIT license,
© Paweł Kuna), at the original sizes, in two colors (dark / light theme).
Usage: outils/generer_icones.py   (downloads the SVGs from jsdelivr,
requires rsvg-convert)."""
import base64, os, subprocess, sys, tempfile, urllib.request

VERSION = "3.19.0"
URL = "https://unpkg.com/@tabler/icons@%s/icons/outline/%s.svg"  # (or cdn.jsdelivr.net/npm/)
ICI = os.path.dirname(os.path.abspath(__file__))
SORTIE = os.path.join(ICI, "..", "siby", "tcl", "moderne", "icones.tcl")

# SCID icon: (Tabler icon, size in pixels, accent?)
CORRESPONDANCE = {
    "tb_open": ("folder-open", 20), "tb_new": ("file-plus", 20), "tb_save": ("device-floppy", 20),
    "tb_close": ("folder-x", 20), "tb_finder": ("folder-search", 20), "tb_bkm": ("bookmark", 20),
    "tb_cut": ("cut", 20), "tb_newgame": ("square-plus", 20), "tb_copy": ("copy", 20),
    "tb_paste": ("clipboard", 20), "tb_gfirst": ("chevrons-left", 19), "tb_gprev": ("chevron-left", 18),
    "tb_gnext": ("chevron-right", 18), "tb_glast": ("chevrons-right", 19), "tb_rfilter": ("filter-off", 20),
    "tb_bsearch": ("chess", 20), "tb_hsearch": ("tags", 20), "tb_msearch": ("scale", 20),
    "tb_pgn": ("file-text", 20), "tb_ginfo": ("info-circle", 20), "tb_glist": ("list", 20),
    "tb_tmt": ("trophy", 20), "tb_maint": ("tool", 20), "tb_eco": ("book-2", 20),
    "tb_tree": ("binary-tree", 20), "tb_book": ("book", 20), "tb_engine": ("cpu", 20),
    "tb_crosst": ("table", 20), "tb_comment": ("message", 20), "tb_help": ("help-circle", 24),
    "tb_help_small": ("help-circle", 20),
    "tb_start": ("player-skip-back", 30), "tb_prev": ("chevron-left", 30), "tb_next": ("chevron-right", 30),
    "tb_end": ("player-skip-forward", 30), "tb_invar": ("arrow-ramp-right", 30), "tb_outvar": ("arrow-back-up", 30),
    "tb_addvar": ("git-branch", 30), "tb_flip": ("arrows-up-down", 30), "tb_gameinfo": ("info-square", 30),
    "tb_coords": ("border-outer", 30), "tb_trial": ("flask", 30), "tb_trial_on": ("flask", 30, True),
    "tb_windows": ("layout-grid", 30),
    "autoplay_off": ("player-track-next", 30), "autoplay_on": ("player-stop", 30, True),
    "tb_cpu": ("cpu-2", 24), "tb_training": ("school", 30), "tb_addmove": ("arrow-bar-right", 27),
    "tb_update": ("refresh", 24), "tb_annotate": ("pencil", 26), "tb_play": ("player-play", 24),
    "tb_pause": ("player-pause", 24), "tb_addallvars": ("git-merge", 30), "tb_lockengine": ("lock", 30),
    # new icons (created if they do not exist): time control filter
    "cad_toutes": ("chess", 20), "cad_blitz": ("bolt", 20), "cad_rapide": ("clock", 20),
    "cad_lente": ("hourglass", 20), "cad_corr": ("mail", 20),
    # threat (like Lichess: gray target, red when active)
    "menace_off": ("focus-2", 22), "menace_on": ("focus-2", 22, "#e0443e"),
    # board navigation unavailable (start / end of the game): dimmed, instead
    # of the hatching Windows draws on disabled buttons
    "tb_start_dim": ("player-skip-back", 30, "doux"), "tb_prev_dim": ("chevron-left", 30, "doux"),
    "tb_next_dim": ("chevron-right", 30, "doux"), "tb_end_dim": ("player-skip-forward", 30, "doux"),
    # up / down arrows (engine lists, ECO, bookmarks)
    "bookmark_up": ("arrow-up", 24), "bookmark_down": ("arrow-down", 24),
}
# scale factors: 1 (100 %), 1.5 (150 %) and 2 (200 %) screens; Siby picks
# the set matching the screen (sharp icons on scaled Windows screens)
FACTEURS = (1, 1.5, 2)
# theme colors (tcl/moderne/theme.tcl): text and accent
COULEURS = {"sombre": ("#d6d6d6", "#57c8ff"), "clair": ("#3a3a3a", "#005fb8")}
# dimmed color ("doux"): unavailable buttons
DOUX = {"sombre": "#5c5c5c", "clair": "#b8b8b8"}

def svg(nom, cache):
    if nom not in cache:
        with urllib.request.urlopen(URL % (VERSION, nom), timeout=30) as r:
            cache[nom] = r.read().decode()
    return cache[nom]

def rendu(texte, taille, couleur, dossier):
    # icon drawn at 80% of the size, centered (the original icons have a margin)
    interieur = max(12, round(taille * 0.8))
    s = texte.replace("currentColor", couleur)
    s = s.replace('width="24"', 'width="%d"' % interieur).replace('height="24"', 'height="%d"' % interieur)
    src = os.path.join(dossier, "i.svg"); png = os.path.join(dossier, "i.png"); out = os.path.join(dossier, "o.png")
    open(src, "w").write(s)
    subprocess.run(["rsvg-convert", "-o", png, src], check=True)
    marge = (taille - interieur) // 2
    subprocess.run(["convert", png, "-background", "none", "-gravity", "center",
                    "-extent", "%dx%d" % (taille, taille), out], check=True)
    return base64.b64encode(open(out, "rb").read()).decode()

def main():
    cache = {}
    with tempfile.TemporaryDirectory() as d:
        lignes = ["", "###", "### Siby: toolbar icons (generated by outils/generer_icones.py)",
                  "### Tabler Icons %s — https://tabler.io/icons — MIT license, © Paweł Kuna." % VERSION,
                  "### They replace the original icons in the dark and light themes (not in",
                  "### the \"classic\" theme). Same image names; sizes for 100 %, 150 % and",
                  "### 200 % screens.", "###", "",
                  "namespace eval ::moderne::icones {", "  variable donnees", "  array set donnees {}", "}", ""]
        for f in FACTEURS:
            for theme, (texte, accent) in COULEURS.items():
                cle = theme if f == 1 else "%s@%s" % (theme, f)
                for nom, spec in sorted(CORRESPONDANCE.items()):
                    tab, taille = spec[0], round(spec[1] * f)
                    couleur = texte
                    if len(spec) > 2:
                        couleur = spec[2] if isinstance(spec[2], str) else accent
                        if couleur == "doux":
                            couleur = DOUX[theme]
                    b64 = rendu(svg(tab, cache), taille, couleur, d)
                    lignes.append("set ::moderne::icones::donnees(%s,%s) {%s}" % (cle, nom, b64))
                print(cle, "ok", file=sys.stderr)
        lignes += ["", "### Scale of the screen: 1, 1.5 or 2 (Windows at 100 %, 150 %, 200 %...)",
                   "proc ::moderne::icones::facteur {} {",
                   "  set f [expr {[tk scaling] / (96 / 72.0)}]",
                   "  if {$f < 1.25} { return 1 } elseif {$f < 1.75} { return 1.5 } else { return 2 }",
                   "}", "",
                   "proc ::moderne::icones::appliquer {} {",
                   "  if {![::moderne::actif]} { return }",
                   "  variable donnees",
                   "  set f [facteur]",
                   "  set cle [expr {$f == 1 ? $::moderne::theme : \"$::moderne::theme@$f\"}]",
                   "  foreach k [array names donnees \"$cle,*\"] {",
                   "    set img [lindex [split $k ,] 1]",
                   "    if {[lsearch -exact [image names] $img] < 0} {",
                   "      # new icons (cad_…): created; the others replace the SCID ones",
                   "      if {[string match cad_* $img] || [string match menace_* $img] || [string match *_dim $img]} { catch {image create photo $img -format png -data $donnees($k)} }",
                   "      continue",
                   "    }",
                   "    catch {$img blank ; $img configure -format png -data $donnees($k)}",
                   "  }", "}", "", "::moderne::icones::appliquer", "", "### End Siby", ""]
        open(SORTIE, "w", encoding="utf-8").write("\n".join(lignes))
    print("written:", SORTIE, file=sys.stderr)

main()
