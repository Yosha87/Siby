#!/bin/sh
# Generates scidvspc/tcl/moderne/cburnett.tcl: the cburnett piece set
# (SVGs from scidvspc/bitmaps/cburnett) rendered as PNG at each board size
# of SCID vs. PC. Each size = a strip of 12 pieces (wp wn wb wr wq wk
# bp bn bb br bq bk), the format expected by setPieceData (tcl/bitmaps.tcl).
# Dependencies: rsvg-convert (librsvg2-bin), ImageMagick (convert), base64.
set -e
RACINE=$(cd "$(dirname "$0")/.." && pwd)
SVG="$RACINE/scidvspc/bitmaps/cburnett"
SORTIE="$RACINE/scidvspc/tcl/moderne/cburnett.tcl"
TMP=$(mktemp -d)
TAILLES="25 30 35 40 45 50 55 60 65 70 75 80 90 100 110 120 130 140 150 160"

mkdir -p "$(dirname "$SORTIE")"
{
  echo "### cburnett piece set — Colin M.L. Burnett, GPL v2+"
  echo "### (SVG via Lichess). File generated by outils/generer_pieces.sh: do not edit."
  echo
  for t in $TAILLES; do
    for p in wP wN wB wR wQ wK bP bN bB bR bQ bK; do
      rsvg-convert -w "$t" -h "$t" "$SVG/$p.svg" -o "$TMP/$p.png"
    done
    convert "$TMP/wP.png" "$TMP/wN.png" "$TMP/wB.png" "$TMP/wR.png" "$TMP/wQ.png" "$TMP/wK.png" \
            "$TMP/bP.png" "$TMP/bN.png" "$TMP/bB.png" "$TMP/bR.png" "$TMP/bQ.png" "$TMP/bK.png" \
            -background none +append -strip "PNG32:$TMP/bande.png"
    echo "set pieceImageData(Cburnett,$t) {"
    base64 -w 76 "$TMP/bande.png"
    echo "}"
  done
} > "$SORTIE"
rm -rf "$TMP"
echo "Written: $SORTIE ($(du -h "$SORTIE" | cut -f1))"
