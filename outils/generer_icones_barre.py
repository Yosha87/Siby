#!/usr/bin/env python3
"""Icons of Siby's left bar (My databases, Lab, Broadcasts, Play), drawn as
images of the same size: fonts draw the symbols at different sizes, and
Windows turns some of them into colour emoji. Writes
siby/tcl/moderne/navicones.tcl (base64 PNG, dark and light themes)."""
import base64, io, math, os
from PIL import Image, ImageDraw, ImageFont

S, OUT = 96, 22          # drawn at 96 px, shown at 22 px
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

def bases(d, col):
    # a database: a cylinder, three stacked discs (as En Croissant; the
    # framed list read as a document, Yosha 2026-11-02)
    x0, x1, w = 16, 80, 7
    d.ellipse([x0, 12, x1, 36], outline=col, width=w)
    for y in (36, 60):
        d.arc([x0, y - 12, x1, y + 12], 0, 180, fill=col, width=w)
    d.line([x0 + 3, 24, x0 + 3, 72], fill=col, width=w)
    d.line([x1 - 3, 24, x1 - 3, 72], fill=col, width=w)
    d.arc([x0, 60, x1, 84], 0, 180, fill=col, width=w)

def classeur(d, col):
    # binders of My databases (not the computer's folders, Yosha
    # 2026-11-05): two lever-arch files side by side, the left one leaning,
    # each with its label (lines) and its finger hole cut out
    vide = (0, 0, 0, 0)
    def un(ox, oy, w, h, angle):
        # (u, v) in the binder (from its bottom right corner, v upwards)
        a = math.radians(angle)
        def p(u, v):
            return (ox - u * math.cos(a) - v * math.sin(a), oy + u * math.sin(a) - v * math.cos(a))
        def rect(u0, v0, u1, v1, fill):
            d.polygon([p(u0, v0), p(u1, v0), p(u1, v1), p(u0, v1)], fill=fill)
        rect(0, 0, w, h, col)
        # the label and its lines
        m = w * 0.2
        rect(m, h * 0.52, w - m, h * 0.9, vide)
        for k in (0.62, 0.71, 0.80):
            rect(m + 4, h * k, w - m - 4, h * k + 4, col)
        # the finger hole
        cx, cy = p(w / 2, h * 0.2)
        r = w * 0.24
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=vide)
    un(87, 90, 34, 80, 0)
    un(49, 90, 30, 76, 14)

def lab(d, col):
    # a microscope, eyepiece, tube and objective on one axis
    A, B = (30, 12), (46, 46)
    dx, dy = B[0]-A[0], B[1]-A[1]; L = math.hypot(dx, dy); ux, uy = dx/L, dy/L
    p = lambda t: (A[0]+ux*t, A[1]+uy*t)
    d.line([p(0), p(L)], fill=col, width=13)
    d.line([p(-11), p(0)], fill=col, width=8)
    d.line([p(L), p(L+10)], fill=col, width=6)
    ox, oy = p(L+10)
    d.rounded_rectangle([ox-20, oy+5, ox+12, oy+11], radius=3, fill=col)
    d.arc([40, 22, 84, 84], start=290, end=95, fill=col, width=7)
    mx, my = p(L*0.45)
    d.line([(mx, my), (66, 25)], fill=col, width=7)
    d.rounded_rectangle([18, 81, 84, 89], radius=4, fill=col)

def direct(d, col):
    # broadcasts: a dot and its waves, ((•)) (it was a red dot, the only
    # coloured icon of the bar, Yosha 2026-11-02)
    d.ellipse([39, 39, 57, 57], fill=col)
    for r in (24, 40):
        for a0, a1 in ((-45, 45), (135, 225)):
            d.arc([48 - r, 48 - r, 48 + r, 48 + r], start=a0, end=a1, fill=col, width=7)

def jouer(d, col):
    # a knight, from DejaVu Sans, as large as the other icons
    f = ImageFont.truetype(FONT, 90)
    x0, y0, x1, y1 = d.textbbox((0, 0), "♞", font=f)
    w, h = x1 - x0, y1 - y0
    # (a margin: at 88 px of 96 the nose touched the edge and was cut once
    # shrunk, Yosha 2026-11-02)
    k = 80 / max(w, h)
    f = ImageFont.truetype(FONT, int(90 * k))
    x0, y0, x1, y1 = d.textbbox((0, 0), "♞", font=f)
    d.text(((S - (x1 - x0)) / 2 - x0, (S - (y1 - y0)) / 2 - y0), "♞", font=f, fill=col)

def deplier(d, col):
    # » : unfold the bar
    for x in (26, 50):
        d.line([(x, 30), (x + 18, 48), (x, 66)], fill=col, width=8, joint="curve")

def replier(d, col):
    # « : fold the bar
    for x in (44, 68):
        d.line([(x, 30), (x - 18, 48), (x, 66)], fill=col, width=8, joint="curve")

def reglages(d, col):
    # settings: three sliders (Toby's settings button; the gear character
    # looked like a molecule in Windows' font, Yosha 2026-11-02)
    for y, x in ((26, 62), (48, 34), (70, 54)):
        d.line([14, y, 82, y], fill=col, width=7)
        d.ellipse([x - 10, y - 10, x + 10, y + 10], fill=(0, 0, 0, 0), outline=col, width=7)

def png(dessin, col, taille=OUT):
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    dessin(ImageDraw.Draw(im), col)
    im = im.resize((taille, taille), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, "PNG")
    return base64.b64encode(b.getvalue()).decode()

themes = {"sombre": (228, 228, 228, 255), "clair": (28, 28, 28, 255)}
# (the fold arrows are quieter, as the text they replace)
doux = {"sombre": (150, 150, 150, 255), "clair": (110, 110, 110, 255)}
lignes = ["### Siby: icons of the left bar (generated by outils/generer_icones_barre.py)",
          "namespace eval ::moderne::navigation {", "  variable iconesData"]
for nom, f in (("bases", bases), ("lab", lab), ("direct", direct), ("jouer", jouer),
               ("deplier", deplier), ("replier", replier), ("reglages", reglages), ("classeur", classeur)):
    for th, col in themes.items():
        c = doux[th] if nom in ("deplier", "replier") else col
        # (also for screens scaled to 150 % and 200 %: the text grows there,
        # the icons must too, as the other icons of Siby)
        for suffixe, taille in (("", OUT), ("@1.5", round(OUT * 1.5)), ("@2", OUT * 2)):
            lignes.append(f"  set iconesData({nom},{th}{suffixe}) {{{png(f, c, taille)}}}")
lignes.append("}")
racine = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(racine, "siby/tcl/moderne/navicones.tcl"), "w") as c:
    c.write("\n".join(lignes) + "\n")
print("ok")
